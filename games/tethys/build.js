#!/usr/bin/env node
// build.js — the build in Node (a port of build.py, so one runtime builds and tests; the outputs are byte-identical).
//
//   node build.js          tethys.html (single file, everything inlined), dev.html (loads src/*.js separately), src/INDEX.md
//   node build.js --test   the same, then node test/lint.js, node test/physics.js, node test/anim.js, node test/steer.js, node test/audio.js, node test/snow.js, node test/sky.js, node test/plankton.js, node test/combat.js, node test/pool.js, node test/registry.js, node test/census.js 40, node test/player.js, node test/live.js and node test/smoke.js (steer, player, live and smoke on both tiers): the four that time themselves first, alone, the rest side by side (JOBS at a time, default the cores, eight at most); SHARD=k/n runs the k-th of n parts; exit 1 on any failure
//
// Build order comes from src/order.txt. src/INDEX.md is generated: every top-level name, its file and line. Do not edit
// INDEX.md by hand; it is rewritten on every build. build.py is kept for the sandbox sessions; keep the two in step.
'use strict';
const fs=require('fs'),path=require('path');
const ROOT=__dirname;
const THREE='<script src="https://cdnjs.cloudflare.com/ajax/libs/three.js/r128/three.min.js"></script>\n';
const read=p=>fs.readFileSync(path.join(ROOT,p),'utf8');
const write=(p,s)=>fs.writeFileSync(path.join(ROOT,p),s,'utf8');

const ORDER=read('src/order.txt').split('\n').map(l=>l.trim()).filter(l=>l&&!l.startsWith('#'));
const parts={};for(const n of ORDER)parts[n]=read('src/'+n+'.js');

// ---------- the two html files ----------
const shell=read('shell.html');
const bundle=THREE+'<script>\n(function(){\n"use strict";\n'+ORDER.map(n=>parts[n]).join('\n')+'\n})();\n</script>';
write('tethys.html',shell.replace('<!--SCRIPTS-->',()=>bundle)); // a function: the bundle may contain $-patterns a string replacement would expand
const dev=THREE+ORDER.map(n=>'<script src="src/'+n+'.js"></script>\n').join('');
write('dev.html',shell.replace('<!--SCRIPTS-->',()=>dev));

// ---------- the name index ----------
// A small tokenizer: comments and string literals are dropped (the code has no template literals), then top-level declarations
// are the const/let/var/function/class keywords seen at bracket depth 0. Who uses a name is a grep away (`grep -n name src/*.js`).
const TOKEN=/\/\/[^\n]*|\/\*[\s\S]*?\*\/|'(?:\\.|[^'\\\n])*'|"(?:\\.|[^"\\\n])*"|[A-Za-z_$][\w$]*|\d[\w.]*|\S/g;
const KEYWORDS=new Set(['const','let','var','function','class']);
function countNL(s,a,b){let n=0;for(let i=a;i<b;i++)if(s.charCodeAt(i)===10)n++;return n;}
function tokens(src){ // [token, line] pairs with comments and strings removed (a string becomes the placeholder '""')
  const out=[];let line=1,pos=0,m;TOKEN.lastIndex=0;
  while((m=TOKEN.exec(src))!==null){const tok=m[0];line+=countNL(src,pos,m.index);pos=m.index+tok.length;
    if(tok.startsWith('//')||tok.startsWith('/*')){}
    else if(tok[0]==="'"||tok[0]==='"')out.push(['""',line]);
    else out.push([tok,line]);
    line+=countNL(tok,0,tok.length);}
  return out;
}
function topLevel(toks){ // {name: line} for every declaration at depth 0
  const names={};let depth=0,i=0;
  while(i<toks.length){const tok=toks[i][0];
    if('([{'.includes(tok))depth++;
    else if(')]}'.includes(tok))depth--;
    else if(depth===0&&KEYWORDS.has(tok)){
      if(tok==='function'||tok==='class'){const j=(i+1<toks.length&&toks[i+1][0]==='*')?i+2:i+1;if(j<toks.length&&/^[A-Za-z_$]/.test(toks[j][0]))names[toks[j][0]]=toks[j][1];}
      else{let j=i+1,d=0,expect=true; // const a=..., b=...;  declarators are the identifiers after the keyword or after a depth-0 comma
        while(j<toks.length){const t=toks[j][0];
          if(d===0&&t===';')break;
          if('([{'.includes(t))d++;
          else if(')]}'.includes(t)){if(d===0)break;d--;}
          else if(d===0&&t===',')expect=true;
          else if(expect&&/^[A-Za-z_$]/.test(t)){names[t]=toks[j][1];expect=false;}
          else if(expect&&t==='=')expect=false;
          j++;}}
    }
    i++;}
  return names;
}
const defs={};for(const n of ORDER)defs[n]=topLevel(tokens(parts[n]));
const home={};for(const n of ORDER)for(const name of Object.keys(defs[n]))if(!(name in home))home[name]=n;
const escapeRe=s=>s.replace(/[.*+?^${}()|[\]\\]/g,'\\$&');
const lines=['# src/INDEX.md — every top-level name and the line it is declared on',
  '',
  'Generated by `python3 build.py`; do not edit. One shared scope: any file may use any name declared in any file',
  '(order only matters for statements that run at load; see `src/order.txt`). To see who uses a name:',
  '`grep -n name src/*.js`. To see which names are unused or undeclared: `node test/lint.js`.',
  ''];
for(const n of ORDER){
  let head=parts[n].split('\n',1)[0];
  head=head.startsWith('//')?head.replace(new RegExp('^//\\s*'+escapeRe(n)+'\\.js\\s*[—-]*\\s*'),'').trim():'';
  lines.push('## '+n+'.js'+(head?' — '+head:''));
  const entries=Object.entries(defs[n]).sort((a,b)=>a[1]-b[1]).filter(([name])=>home[name]===n).map(([name,line])=>'`'+name+'` '+line);
  lines.push(entries.length?entries.join('  '):'(no top-level names)');
  lines.push('');
}
write('src/INDEX.md',lines.join('\n'));
console.log('built tethys.html, dev.html, src/INDEX.md ('+ORDER.length+' files, '+Object.keys(home).length+' top-level names)');

// ---------- tests ----------
// v11.93.3: side by side. The four runs that time themselves and fail on it (physics.js: 20 rigged creatures under 4 ms a frame; audio.js:
// updateAudio under 0.3 ms; snow.js: updatePlankton under 0.6 ms; sky.js: cloudAt under 20 µs) go first, one at a time with nothing else
// running; then the rest, JOBS at a time (default: the machine's cores, eight at most), longest first. Nothing else in a run reads the wall clock (the
// stub's performance.now is the frames'), so sharing the machine changes no other result. Each run gets a temp folder of its own (TMPDIR,
// TMP, TEMP): every test writes its bundle into the OS's temp folder under one fixed name, and two tiers of one test side by side would
// overwrite each other's. A run's output is printed whole when it ends, then a table of every run's time. JOBS=1 is one at a time.
if(process.argv.includes('--test')){
  const os=require('os'),{spawn}=require('child_process');
  const ALONE=[[['test/physics.js'],{},4],[['test/audio.js'],{},20],[['test/snow.js'],{},38],[['test/sky.js'],{},2]]; // the third number: its seconds one at a time on a sandbox CPU (v11.93.3), for the shards
  const SIDE=[[['test/smoke.js'],{},156],[['test/smoke.js'],{TIER:'low'},103],[['test/live.js'],{},89],[['test/live.js'],{TIER:'low'},87],[['test/player.js'],{},56],[['test/census.js','40'],{},55],[['test/falls.js'],{},52],[['test/player.js'],{TIER:'low'},41],[['test/steer.js'],{},25],[['test/steer.js'],{TIER:'low'},18],[['test/anim.js'],{},17],[['test/combat.js'],{},9],[['test/registry.js'],{},5],[['test/pool.js'],{},4],[['test/plankton.js'],{},2],[['test/region.js'],{},1],[['test/lint.js'],{},1]]; // longest first
  // v11.93.4: SHARD=k/n (CI: package.json's "shards", one machine a part) runs the k-th of n parts. The runs are dealt longest first to the part
  // with the fewest seconds so far, ties to the lower part; build.py deals them the same. Each part runs its own timed runs first and alone.
  const SH=/^(\d+)\/(\d+)$/.exec(process.env.SHARD||'');
  if(process.env.SHARD&&!(SH&&+SH[1]>=1&&+SH[1]<=+SH[2])){console.error('SHARD is k/n with 1 <= k <= n, not '+process.env.SHARD);process.exit(1);}
  const part=new Map();if(SH){const load=new Array(+SH[2]).fill(0);for(const r of ALONE.concat(SIDE).sort((a,b)=>b[2]-a[2])){let k=0;for(let i=1;i<load.length;i++)if(load[i]<load[k])k=i;load[k]+=r[2];part.set(r,k+1);}}
  const mine=r=>!SH||part.get(r)===+SH[1],alone=ALONE.filter(mine),side=SIDE.filter(mine);
  const JOBS=Math.max(1,+process.env.JOBS||Math.min(8,os.availableParallelism())),T0=Date.now(),res=[]; // eight at most by default: smoke.js alone (~3 min) is the floor past five or six, and all fifteen at once peak near 9 GB
  const name=([args,env])=>Object.entries(env).map(([k,v])=>k+'='+v+' ').join('')+'node '+args.join(' ');
  const run=r=>new Promise(done=>{const tmp=fs.mkdtempSync(path.join(os.tmpdir(),'tethys-test-')),t0=Date.now(),out=[];let end=false;
    const fin=(code,err)=>{if(end)return;end=true;const s=(Date.now()-t0)/1000;fs.rmSync(tmp,{recursive:true,force:true});if(err)out.push(Buffer.from(String(err)+'\n'));
      process.stdout.write('\n$ '+name(r)+'\n'+Buffer.concat(out).toString()+(code===0?'':'exit '+code+'\n')+'('+s.toFixed(0)+' s)\n');res.push([name(r),code===0,s]);done();};
    const p=spawn(process.execPath,r[0],{cwd:ROOT,env:Object.assign({},process.env,r[1],{TMPDIR:tmp,TMP:tmp,TEMP:tmp})});
    p.stdout.on('data',d=>out.push(d));p.stderr.on('data',d=>out.push(d));p.on('error',e=>fin(-1,e));p.on('close',(code,sig)=>fin(code===null?sig:code));});
  (async()=>{
    console.log('\n'+(alone.length+side.length)+' test runs'+(SH?' (part '+SH[1]+' of '+SH[2]+', SHARD)':'')+': '+alone.length+' that time themselves first, one at a time; then '+side.length+', '+JOBS+' at a time');
    for(const r of alone)await run(r);
    const q=side.slice();await Promise.all(Array.from({length:Math.min(JOBS,q.length)},async()=>{while(q.length)await run(q.shift());}));
    const bad=res.filter(r=>!r[1]);
    console.log('\n'+res.map(([n,ok,s])=>(ok?'ok    ':'FAILED')+s.toFixed(0).padStart(5)+' s  '+n).join('\n'));
    console.log((bad.length?'\nFAILED: '+bad.map(r=>r[0]).join(', '):'\nALL OK')+' ('+((Date.now()-T0)/1000).toFixed(0)+' s, '+JOBS+' at a time'+(SH?', part '+SH[1]+' of '+SH[2]:'')+')');
    process.exitCode=bad.length?1:0; // not process.exit: on Windows a piped stdout is written asynchronously, and exit would cut it
  })();
}
