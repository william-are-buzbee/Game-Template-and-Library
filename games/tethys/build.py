#!/usr/bin/env python3
"""Builds the game and the name index.

  python3 build.py          tethys.html (single file, everything inlined), dev.html (loads src/*.js separately), src/INDEX.md
  python3 build.py --test   the same, then node test/lint.js, node test/physics.js, node test/anim.js, node test/steer.js, node test/audio.js, node test/snow.js, node test/sky.js, node test/plankton.js, node test/records.js, node test/maps.js, node test/ledger.js, node test/combat.js, node test/pool.js, node test/registry.js, node test/census.js 40, node test/player.js, node test/live.js and node test/smoke.js (steer, player, live and smoke on both tiers): the four that time themselves first, alone, the rest side by side (JOBS at a time, default the cores, eight at most); SHARD=k/n runs the k-th of n parts; exit 1 on any failure

Build order comes from src/order.txt. src/INDEX.md is generated: every top-level name, its file and line, and which other
files use it. Do not edit INDEX.md by hand; it is rewritten on every build.
"""
import os, re, subprocess, sys
ROOT = os.path.dirname(os.path.abspath(__file__))
THREE = '<script src="https://cdnjs.cloudflare.com/ajax/libs/three.js/r128/three.min.js"></script>\n'

def read(p): return open(os.path.join(ROOT, p), encoding='utf-8').read()
def write(p, s): open(os.path.join(ROOT, p), 'w', encoding='utf-8').write(s)

ORDER = [l.strip() for l in read('src/order.txt').split('\n') if l.strip() and not l.strip().startswith('#')]
parts = {n: read('src/%s.js' % n) for n in ORDER}

# ---------- the two html files ----------
shell = read('shell.html')
bundle = THREE + '<script>\n(function(){\n"use strict";\n' + '\n'.join(parts[n] for n in ORDER) + '\n})();\n</script>'
write('tethys.html', shell.replace('<!--SCRIPTS-->', bundle))
dev = THREE + ''.join('<script src="src/%s.js"></script>\n' % n for n in ORDER)
write('dev.html', shell.replace('<!--SCRIPTS-->', dev))

# ---------- the name index ----------
# A small tokenizer: comments and string literals are dropped (the code has no regex or template literals), then top-level
# declarations are the const/let/var/function/class keywords seen at bracket depth 0. Who uses a name is a grep away
# (`grep -n name src/*.js`); an index of that would need scope analysis to be exact, and test/lint.js has it if wanted.
TOKEN = re.compile(r'''//[^\n]*|/\*.*?\*/|'(?:\\.|[^'\\\n])*'|"(?:\\.|[^"\\\n])*"|[A-Za-z_$][\w$]*|\d[\w.]*|\S''', re.S)
KEYWORDS = {'const', 'let', 'var', 'function', 'class'}

def tokens(src):
    """(token, line) pairs with comments and strings removed (a string becomes the placeholder '""')."""
    out, line, pos = [], 1, 0
    for m in TOKEN.finditer(src):
        tok = m.group(0)
        line += src.count('\n', pos, m.start()); pos = m.end()
        if tok.startswith('//') or tok.startswith('/*'):
            pass
        elif tok[0] in '\'"':
            out.append(('""', line))
        else:
            out.append((tok, line))
        line += tok.count('\n')
    return out

def top_level(toks):
    """{name: line} for every declaration at depth 0."""
    names, depth, i = {}, 0, 0
    while i < len(toks):
        tok, line = toks[i]
        if tok in '([{': depth += 1
        elif tok in ')]}': depth -= 1
        elif depth == 0 and tok in KEYWORDS:
            if tok in ('function', 'class'):
                j = i + 2 if i + 1 < len(toks) and toks[i + 1][0] == '*' else i + 1  # function* name
                if j < len(toks) and re.match(r'[A-Za-z_$]', toks[j][0]): names[toks[j][0]] = toks[j][1]
            else:  # const a=..., b=...;  declarators are the identifiers after the keyword or after a depth-0 comma
                j, d, expect = i + 1, 0, True
                while j < len(toks):
                    t = toks[j][0]
                    if d == 0 and t == ';': break
                    if t in '([{': d += 1
                    elif t in ')]}':
                        if d == 0: break
                        d -= 1
                    elif d == 0 and t == ',': expect = True
                    elif expect and re.match(r'[A-Za-z_$]', t): names[t] = toks[j][1]; expect = False
                    elif expect and t in ('=',): expect = False
                    j += 1
        i += 1
    return names

toks = {n: tokens(parts[n]) for n in ORDER}
defs = {n: top_level(toks[n]) for n in ORDER}
home = {}
for n in ORDER:
    for name in defs[n]: home.setdefault(name, n)

lines = ['# src/INDEX.md — every top-level name and the line it is declared on',
         '',
         'Generated by `python3 build.py`; do not edit. One shared scope: any file may use any name declared in any file',
         '(order only matters for statements that run at load; see `src/order.txt`). To see who uses a name:',
         '`grep -n name src/*.js`. To see which names are unused or undeclared: `node test/lint.js`.',
         '']
for n in ORDER:
    head = parts[n].split('\n', 1)[0]
    head = re.sub(r'^//\s*' + re.escape(n) + r'\.js\s*[—-]*\s*', '', head).strip() if head.startswith('//') else ''
    lines.append('## %s.js%s' % (n, (' — ' + head) if head else ''))
    entries = []
    for name, line in sorted(defs[n].items(), key=lambda kv: kv[1]):
        if home[name] != n: continue
        entries.append('`%s` %d' % (name, line))
    lines.append('  '.join(entries) if entries else '(no top-level names)')
    lines.append('')
write('src/INDEX.md', '\n'.join(lines))
print('built tethys.html, dev.html, src/INDEX.md (%d files, %d top-level names)' % (len(ORDER), len(home)))

# ---------- tests ----------
# v11.93.3: side by side, as build.js does (its comment has the why): the four runs that time themselves first, one at a time with nothing
# else running; then the rest, JOBS at a time (default the cores, eight at most), longest first; each with a temp folder of its own, its output printed
# whole when it ends, then a table of every run's time.
if '--test' in sys.argv:
    import shutil, tempfile, threading, time
    from concurrent.futures import ThreadPoolExecutor
    ALONE = [(['test/physics.js'], {}, 4), (['test/audio.js'], {}, 20), (['test/snow.js'], {}, 38), (['test/sky.js'], {}, 2)]  # the third number: its seconds one at a time, as build.js
    SIDE = [(['test/smoke.js'], {}, 164), (['test/smoke.js'], {'TIER': 'low'}, 108), (['test/live.js'], {}, 100), (['test/live.js'], {'TIER': 'low'}, 98), (['test/player.js'], {}, 56), (['test/census.js', '40'], {}, 61), (['test/ledger.js'], {}, 135), (['test/falls.js'], {}, 59), (['test/maps.js'], {}, 20), (['test/player.js'], {'TIER': 'low'}, 41), (['test/steer.js'], {}, 25), (['test/steer.js'], {'TIER': 'low'}, 18), (['test/anim.js'], {}, 17), (['test/combat.js'], {}, 9), (['test/registry.js'], {}, 5), (['test/pool.js'], {}, 4), (['test/plankton.js'], {}, 2), (['test/origins.js'], {}, 22), (['test/horizon.js'], {}, 13), (['test/records.js'], {}, 2), (['test/region.js'], {}, 1), (['test/lint.js'], {}, 1)]
    # v11.93.4: SHARD=k/n runs the k-th of n parts, dealt as build.js deals them: longest first to the part with the fewest seconds, ties low
    SH = re.match(r'^(\d+)/(\d+)$', os.environ.get('SHARD', ''))
    if os.environ.get('SHARD') and not (SH and 1 <= int(SH.group(1)) <= int(SH.group(2))):
        print('SHARD is k/n with 1 <= k <= n, not ' + os.environ['SHARD'], file=sys.stderr); sys.exit(1)
    part = {}
    if SH:
        load = [0] * int(SH.group(2))
        for r in sorted(ALONE + SIDE, key=lambda r: -r[2]):
            k = load.index(min(load)); load[k] += r[2]; part[id(r)] = k + 1
    def mine(r): return not SH or part[id(r)] == int(SH.group(1))
    alone, side = [r for r in ALONE if mine(r)], [r for r in SIDE if mine(r)]
    JOBS = max(1, int(os.environ.get('JOBS') or 0) or min(8, os.cpu_count() or 1))  # eight at most by default, as build.js
    T0, res, lock = time.time(), [], threading.Lock()
    def name(r): return ''.join('%s=%s ' % kv for kv in r[1].items()) + 'node ' + ' '.join(r[0])
    def run(r):
        tmp, t0 = tempfile.mkdtemp(prefix='tethys-test-'), time.time()
        p = subprocess.run(['node'] + r[0], cwd=ROOT, env={**os.environ, **r[1], 'TMPDIR': tmp, 'TMP': tmp, 'TEMP': tmp}, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
        s = time.time() - t0
        shutil.rmtree(tmp, ignore_errors=True)
        with lock:
            sys.stdout.write('\n$ %s\n%s%s(%.0f s)\n' % (name(r), p.stdout.decode('utf-8', 'replace'), '' if p.returncode == 0 else 'exit %d\n' % p.returncode, s)); sys.stdout.flush()
            res.append((name(r), p.returncode == 0, s))
    print('\n%d test runs%s: %d that time themselves first, one at a time; then %d, %d at a time' % (len(alone) + len(side), ' (part %s of %s, SHARD)' % SH.groups() if SH else '', len(alone), len(side), JOBS)); sys.stdout.flush()
    for r in alone: run(r)
    if side:
        with ThreadPoolExecutor(min(JOBS, len(side))) as ex: list(ex.map(run, side))
    bad = [r for r in res if not r[1]]
    print('\n' + '\n'.join('%s%5.0f s  %s' % ('ok    ' if ok else 'FAILED', s, n) for n, ok, s in res))
    print('%s (%.0f s, %d at a time%s)' % ('\nFAILED: ' + ', '.join(r[0] for r in bad) if bad else '\nALL OK', time.time() - T0, JOBS, ', part %s of %s' % SH.groups() if SH else ''))
    sys.exit(1 if bad else 0)
