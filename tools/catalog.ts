// tools/catalog.ts — writes CATALOG.md: every package, game and lab, what it is, what it uses and who uses it.
//   node tools/catalog.ts            rewrite CATALOG.md
//   node tools/catalog.ts --check    exit 1 if CATALOG.md is not what it would write (CI runs this)
// The source of truth is each workspace's package.json (`description`, and its `@wb/*` dependencies), so the
// catalog cannot drift from the code: change the package.json and rerun this.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { FOLDER, ROOT, SITE, liveUrl, workspaces, type Kind, type Workspace } from './lib/workspaces.ts';

const HEAD: Record<Kind, { title: string; blurb: string; none: string }> = {
  package: {
    title: 'Packages',
    blurb: 'Proven systems used by two or more projects. Use these before writing anything they cover (CLAUDE.md, *The promotion rule*).',
    none: 'None yet. A package appears when a second project needs something a first one has.',
  },
  game: { title: 'Games', blurb: 'Real projects: tests, a CLAUDE.md of their own, the architecture rules.', none: 'None yet.' },
  lab: { title: 'Labs', blurb: 'One-shots, model trials and tech demos. The only rule is that they build.', none: 'None yet.' },
};

function cell(s: string): string {
  return s.replace(/</g, '&lt;').replace(/\|/g, '\\|').replace(/\n+/g, ' ').trim() || '—';
}

function render(all: Workspace[]): string {
  const byPkg = new Map(all.map(w => [w.pkgName, w]));
  const usedBy = new Map<string, string[]>();
  for (const w of all) for (const u of w.uses) usedBy.set(u, [...(usedBy.get(u) ?? []), w.dir]);
  const link = (pkgName: string) => {
    const w = byPkg.get(pkgName);
    return w ? `[${w.name}](${w.dir}/)` : `\`${pkgName}\``;
  };

  const lines = [
    '# Catalog',
    '',
    'Everything in this repo, generated by `npm run catalog` from each workspace\'s `package.json`. Do not edit by hand:',
    'CI fails when this file is out of date.',
    '',
    `Live site: ${SITE}`,
  ];
  for (const kind of ['package', 'game', 'lab'] as Kind[]) {
    const list = all.filter(w => w.kind === kind);
    lines.push('', `## ${HEAD[kind].title}`, '', HEAD[kind].blurb, '');
    if (!list.length) {
      lines.push(`_${HEAD[kind].none}_`);
      continue;
    }
    if (kind === 'package') {
      lines.push('| package | what it is | used by |', '|---|---|---|');
      for (const w of list) {
        const users = (usedBy.get(w.pkgName) ?? []).map(d => `[${d.split('/')[1]}](${d}/)`).join(', ');
        lines.push(`| [\`${w.pkgName}\`](${w.dir}/) | ${cell(w.description)} | ${users || '—'} |`);
      }
    } else {
      lines.push(`| ${kind} | what it is | uses | live |`, '|---|---|---|---|');
      for (const w of list) {
        const url = liveUrl(w);
        lines.push(`| [${w.name}](${w.dir}/) | ${cell(w.description)} | ${w.uses.map(link).join(', ') || '—'} | ${url ? `[open](${url})` : '—'} |`);
      }
    }
  }
  return lines.join('\n') + '\n';
}

function problems(all: Workspace[]): string[] {
  const out: string[] = [];
  for (const w of all) {
    if (!w.description.trim()) out.push(`${w.dir}: package.json has no "description" (one line: what it is)`);
    if (w.pkgName !== `@wb/${w.name}`) out.push(`${w.dir}: package.json "name" should be "@wb/${w.name}", is "${w.pkgName}"`);
  }
  return out;
}

const all = workspaces();
const bad = problems(all);
if (bad.length) {
  console.error(bad.join('\n'));
  process.exit(1);
}
const file = join(ROOT, 'CATALOG.md');
const next = render(all);
if (process.argv.includes('--check')) {
  const now = existsSync(file) ? readFileSync(file, 'utf8') : '';
  if (now !== next) {
    console.error('CATALOG.md is out of date: run `npm run catalog` and commit the result.');
    process.exit(1);
  }
  console.log(`CATALOG.md is current (${all.length} workspaces in ${Object.values(FOLDER).join(', ')}).`);
} else {
  writeFileSync(file, next);
  console.log(`CATALOG.md written (${all.length} workspaces).`);
}
