// tools/site.ts — assembles the published site in _site/ from what `npm run build` left in each workspace's dist/.
//   node tools/site.ts
// _site/index.html lists every game and lab (from the same package.json fields as CATALOG.md) with a link to each;
// each build is copied to _site/<folder>/<name>/. A workspace with no dist/ is listed without a link and warned
// about, so one broken lab does not take the whole site down. .github/publish.sh puts _site on the gh-pages branch.
import { cpSync, existsSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { execSync } from 'node:child_process';
import { ROOT, workspaces, type Kind, type Workspace } from './lib/workspaces.ts';

const out = join(ROOT, '_site');
rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

const shown = workspaces().filter(w => w.kind !== 'package');
const built = new Set<string>();
for (const w of shown) {
  const dist = join(ROOT, w.dir, 'dist');
  if (!existsSync(join(dist, 'index.html'))) {
    console.warn(`warning: ${w.dir} has no dist/index.html (run \`npm run build -w ${w.dir}\`); listed without a link`);
    continue;
  }
  cpSync(dist, join(out, w.dir), { recursive: true });
  built.add(w.dir);
}

const esc = (s: string) => s.replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]!);
let commit = process.env.GITHUB_SHA ?? '';
try {
  commit ||= execSync('git rev-parse HEAD', { cwd: ROOT, stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim();
} catch {
  /* not a git checkout: leave it out */
}
const pr = process.env.PREVIEW_PR;

const section = (kind: Kind, title: string, blurb: string) => {
  const list = shown.filter(w => w.kind === kind);
  const item = (w: Workspace) =>
    `<li>${built.has(w.dir) ? `<a href="${w.dir}/">${esc(w.name)}</a>` : `<span class="off">${esc(w.name)}</span>`}<p>${esc(w.description)}</p></li>`;
  return `<section><h2>${title}</h2><p class="blurb">${blurb}</p>${list.length ? `<ul>${list.map(item).join('')}</ul>` : '<p class="none">None yet.</p>'}</section>`;
};

writeFileSync(
  join(out, 'index.html'),
  `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Games and labs</title>
<style>
:root{--bg:#f6f5f2;--fg:#1d1c1a;--dim:#6b6860;--line:#dcd9d2;--link:#1f5fbf}
@media (prefers-color-scheme:dark){:root{--bg:#141413;--fg:#ecebe7;--dim:#9a978f;--line:#2e2d2a;--link:#8db4ff}}
*{box-sizing:border-box}body{margin:0;background:var(--bg);color:var(--fg);font:16px/1.5 system-ui,sans-serif}
main{max-width:760px;margin:0 auto;padding:40px 16px 64px}h1{font-size:28px;margin:0 0 4px}h2{font-size:18px;margin:36px 0 4px}
.sub,.blurb,.none,footer{color:var(--dim)}.blurb{margin:0 0 12px;font-size:14px}ul{list-style:none;margin:0;padding:0}
li{padding:12px 0;border-top:1px solid var(--line)}li p{margin:2px 0 0;color:var(--dim);font-size:14px}
a{color:var(--link);font-weight:600;text-decoration:none}a:hover{text-decoration:underline}.off{font-weight:600;color:var(--dim)}
footer{margin-top:40px;font-size:12px}code{font:12px ui-monospace,monospace}
</style>
</head>
<body>
<main>
<h1>Games and labs</h1>
<p class="sub">${pr ? `Preview of pull request #${esc(pr)}.` : 'Everything in the repository, built from main.'} Code, packages and the catalog are in the repository.</p>
${section('game', 'Games', 'Real projects.')}
${section('lab', 'Labs', 'One-shots, model trials and tech demos.')}
<footer>${commit ? `Built from <code>${esc(commit.slice(0, 7))}</code>. ` : ''}Generated by tools/site.ts.</footer>
</main>
</body>
</html>
`,
);
console.log(`_site/ assembled: ${built.size} of ${shown.length} games and labs built.`);
